    function genererGrapheAuteurs(references) {
        if (!references || references.length === 0) {
            console.warn("La liste de références est vide.");
            return { nodes: [], links: [], centralAuthor: null };
        }

        const allAuthors = new Set();
        const authorPaperCount = {}; 

        const authorCollaborations = {}; 
        const collaborationWeights = {}; 

        references.forEach(ref => {
            ref.auteurs.forEach(auteur => {
                allAuthors.add(auteur);
                authorPaperCount[auteur] = (authorPaperCount[auteur] || 0) + 1;
                if (!authorCollaborations[auteur]) {
                    authorCollaborations[auteur] = new Set();
                }
            });

            
            for (let i = 0; i < ref.auteurs.length; i++) {
                for (let j = i + 1; j < ref.auteurs.length; j++) {
                    const auteur1 = ref.auteurs[i];
                    const auteur2 = ref.auteurs[j];

                    
                    authorCollaborations[auteur1].add(auteur2);
                    authorCollaborations[auteur2].add(auteur1);

                    const linkKey = [auteur1, auteur2].sort().join('---');
                    collaborationWeights[linkKey] = (collaborationWeights[linkKey] || 0) + 1;
                }
            }
        });

        let commonAuthor = null;
        let maxFrequency = 0;
        let mostFrequentAuthor = null;

        for (const auteur of allAuthors) {
            if (authorPaperCount[auteur] === references.length) {
                commonAuthor = auteur;
                break;
            }
            if (authorPaperCount[auteur] > maxFrequency) {
                maxFrequency = authorPaperCount[auteur];
                mostFrequentAuthor = auteur;
            }
        }

        const centralAuthor = commonAuthor || mostFrequentAuthor;

        const nodes = Array.from(allAuthors).map(auteur => ({
            id: auteur,
            label: auteur,
            isCentral: auteur === centralAuthor,
            paperCount: authorPaperCount[auteur],
   
            collaborationCount: authorCollaborations[auteur] ? authorCollaborations[auteur].size : 0
        }));

        const links = [];
        for (const linkKey in collaborationWeights) {
            const [sourceId, targetId] = linkKey.split('---');
            links.push({
                source: sourceId,
                target: targetId,
                weight: collaborationWeights[linkKey] 
            });
        }

        return { nodes, links, centralAuthor };
    }


    document.addEventListener('DOMContentLoaded', () => {
        const graphData = genererGrapheAuteurs(referencesBibliographiques);

        const container = document.getElementById('graph-container');
        const width = container.clientWidth;
        const height = container.clientHeight;

        const svg = d3.select(container)
            .append("svg")
            .attr("viewBox", [0, 0, width, height]); 

        const g = svg.append("g");

        
        const simulation = d3.forceSimulation(graphData.nodes)
            .force("link", d3.forceLink(graphData.links).id(d => d.id).distance(d => 150 + d.weight * 100))
            .force("charge", d3.forceManyBody().strength(-400))
            .force("center", d3.forceCenter(width / 2, height / 2))
            .force("collide", d3.forceCollide().radius(d => 10 + d.collaborationCount * 1.5)); // Empêche les nœuds de se chevaucher

    
        const link = g.append("g")
            .attr("class", "links")
            .selectAll("line")
            .data(graphData.links)
            .enter().append("line")
            .attr("class", "link")
            .attr("stroke-width", d => Math.sqrt(d.weight) * 2)
            .on("mouseover", (event, d) => showTooltip(event, d, 'link'))
            .on("mouseout", hideTooltip);

        
        const node = g.append("g")
            .attr("class", "nodes")
            .selectAll("circle")
            .data(graphData.nodes)
            .enter().append("circle")
            .attr("r", d => 8 + d.collaborationCount * 1.5)
            .attr("class", d => d.isCentral ? "node central" : "node")
            .call(d3.drag()
                .on("start", dragstarted)
                .on("drag", dragged)
                .on("end", dragended))
            .on("mouseover", (event, d) => showTooltip(event, d, 'node'))
            .on("mouseout", hideTooltip);

        const labels = g.append("g")
            .attr("class", "labels")
            .selectAll("text")
            .data(graphData.nodes)
            .enter().append("text")
            .attr("class", "node-label")
            .text(d => d.label)
            .attr("dx", d => 10 + d.collaborationCount * 1.5)
            .attr("dy", ".35em")
            .on("mouseover", (event, d) => showTooltip(event, d, 'node'))
            .on("mouseout", hideTooltip);

 
        simulation.on("tick", () => {
            link
                .attr("x1", d => d.source.x)
                .attr("y1", d => d.source.y)
                .attr("x2", d => d.target.x)
                .attr("y2", d => d.target.y);

            node
                .attr("cx", d => d.x)
                .attr("cy", d => d.y);

            labels
                .attr("x", d => d.x)
                .attr("y", d => d.y);
        });

      
        function dragstarted(event, d) {
            if (!event.active) simulation.alphaTarget(0.3).restart();
            d.fx = d.x;
            d.fy = d.y;
        }

        function dragged(event, d) {
            d.fx = event.x;
            d.fy = event.y;
        }

        function dragended(event, d) {
            if (!event.active) simulation.alphaTarget(0);
            d.fx = null;
            d.fy = null;
        }

     
        const tooltip = d3.select("#tooltip");

        function showTooltip(event, d, type) {
            let content = '';
            if (type === 'node') {
                content = `<strong>${d.label}</strong><br/>
                               Papers: ${d.paperCount}<br/>
                               Collaborations: ${d.collaborationCount}`;
                if (d.isCentral) {
                    content += '<br/>(Central Author)';
                }
            } else if (type === 'link') {
                content = `<strong>Collaboration</strong><br/>
                               ${d.source.id} & ${d.target.id}<br/>
                               Papers co-authored: ${d.weight}`;
            }

            tooltip.html(content)
                .style("left", (event.pageX + 15) + "px")
                .style("top", (event.pageY - 25) + "px")
                .style("opacity", 1);
        }

        function hideTooltip() {
            tooltip.style("opacity", 0);
        }


        const zoomBehavior = d3.zoom()
            .scaleExtent([0.1, 10])
            .on("zoom", (event) => {
                g.attr("transform", event.transform);
            });
        svg.call(zoomBehavior);

        if (graphData.centralAuthor) {
            const centralNode = graphData.nodes.find(n => n.id === graphData.centralAuthor);
            if (centralNode) {
        
                centralNode.x = width / 2;
                centralNode.y = height / 2;
                centralNode.fx = width / 2; 
                centralNode.fy = height / 2;


                setTimeout(() => {
                    const initialScale = 0.22; 
                    const initialTransform = d3.zoomIdentity
                        .translate(width / 2 - centralNode.x * initialScale, height / 2 - centralNode.y * initialScale)
                        .scale(initialScale);
                    svg.transition().duration(750).call(zoomBehavior.transform, initialTransform);
                }, 500); 
            }
        }
    });